const {chromium}=require(process.env.PLAYWRIGHT || 'playwright');
const {mkdirSync}=require('node:fs');
const assert=require('node:assert/strict');
const base=process.env.QA_URL || 'http://127.0.0.1:8879';
const out=process.env.QA_OUT || '/tmp/jianghai-qa';
mkdirSync(out,{recursive:true});
(async()=>{
  const browser=await chromium.launch({executablePath:process.env.CHROME});
  try {
    for(const width of [1440,390]){
      const height=width===1440?1000:844;
      const ctx=await browser.newContext({viewport:{width,height},isMobile:width===390,hasTouch:width===390});
      const page=await ctx.newPage(), errors=[];
      page.on('pageerror',e=>errors.push(e.message));
      page.on('response',r=>{if(r.url().startsWith(base)&&r.status()>=400)errors.push(`${r.status()} ${r.url()}`);});
      await page.goto(`${base}/?qa=release`);
      await page.waitForURL('**/v3/?qa=release');
      const intro=page.locator('#introVeil');
      await intro.waitFor();
      assert.equal(await intro.locator('.intro-title>span').allTextContents().then(s=>s.join('')),'张謇诗路');
      await page.locator('.intro-tagline').evaluate(el=>Promise.all(el.getAnimations().map(a=>a.finished)));
      await page.screenshot({path:`${out}/${width}-merged-01-ink.png`});
      await intro.click();
      await intro.waitFor({state:'hidden'});
      const map=page.locator('.tour-hero-actions a').first();
      assert.equal(await page.locator('.tour-hero-actions a').count(),2);
      assert.equal(await map.getAttribute('href'),'exhibit.html#map');
      const box=await map.boundingBox();
      assert.ok(box.y>0&&box.y+box.height<height&&box.height>=44,'map is on-screen and usable without scrolling');
      assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth),width);
      assert.equal(await page.locator('#archive [data-poem]').count(),8);
      assert.equal(await page.locator('#seven-gates [data-entrance-station]').count(),7);
      await page.screenshot({path:`${out}/${width}-merged-02-home.png`});
      await map.click();
      await page.waitForURL('**/v3/exhibit.html#map');
      await page.locator('#atlas .geo-point').first().waitFor();
      await page.goto(`${base}/v3/#two-views`);
      const guide=page.locator('#two-views');
      assert.deepEqual(await guide.locator('h3').allTextContents(),['诗歌档案','七境漫游','地方文献展']);
      await page.evaluate(()=>{document.activeElement?.blur();document.getElementById('two-views').scrollIntoView({behavior:'instant'});});
      await page.screenshot({path:`${out}/${width}-merged-04-guide.png`});
      await guide.locator('.mode-card-walk').click();
      await page.waitForURL('**/#seven-gates');
      await page.locator('#seven-gates [data-entrance-station="haimen"]').click();
      await page.locator('#stationFeature').click();
      await page.locator('#stationDialog').waitFor();
      const nav=new URL(await page.locator('#stationTravel').getAttribute('href'));
      assert.equal(nav.hostname,'uri.amap.com');
      assert.match(nav.searchParams.get('keyword'),/张謇纪念馆/);
      assert.equal(await page.locator('#stationExhibit').getAttribute('href'),'exhibit.html#d=haimen');
      await page.locator('#stationPassport').click();
      await page.waitForURL('**/#passport');
      assert.ok(await page.locator('#stationDialog').isHidden());
      await page.getByRole('link',{name:'回诗歌档案写观察'}).click();
      await page.waitForURL('**/#archive');
      await page.locator('#archive [data-poem="1"]').click();
      await page.locator('#dialogContent audio').waitFor();
      await page.getByRole('button',{name:'看这首诗的影像'}).click();
      await page.locator('#dialogContent video').waitFor();
      await page.locator('#dialogViews [data-view="poem"]').click();
      await page.locator('.poem-next').getByRole('button',{name:'看诗句关系'}).click();
      await page.locator('#dialogContent .graph-preview img').waitFor();
      await page.locator('#dialogViews [data-view="poem"]').click();
      await page.getByRole('button',{name:'记录这首诗的观察'}).click();
      await page.locator('#activityNote').waitFor();
      await page.locator('#dialogClose').click();
      await page.goto(`${base}/v3/#two-views`);
      await guide.locator('.mode-card-research').click();
      await page.waitForURL('**/v3/exhibit.html#poems');
      assert.equal(await page.locator('#poems .poem-links a').count(),8);
      await page.locator('#poems a[href="index.html#read-poem-3"]').click();
      await page.waitForURL('**/v3/index.html#read-poem-3');
      assert.equal(await page.locator('#poemDialog[open] #dialogTitle').innerText(),'《盆松》');
      await page.goto(`${base}/v3/#two-views`);
      await guide.locator('.mode-card-exhibit').click();
      await page.waitForURL('**/v3/exhibit.html#books');
      await page.locator('#book-grid article').first().waitFor();
      await page.goto(`${base}/v3/exhibit.html#map`);
      await page.screenshot({path:`${out}/${width}-merged-03-exhibit.png`});
      assert.ok(await page.locator('#atlas .geo-point').count()>0);
      await page.locator('#districts [data-region="haimen"]').click();
      await page.locator('#station-body [data-place="haimen-3"]').click();
      await page.getByRole('button',{name:'查这处的书目与页码'}).click();
      assert.equal(await page.locator('#place-content h3').first().evaluate(el=>el===document.activeElement),true);
      assert.match(await page.locator('#place-content .reference-list').innerText(),/ISBN.*页/);
      await page.goto(`${base}/v3/#d=rudong`);
      await page.waitForURL('**/v3/exhibit.html#d=rudong');
      assert.match(await page.locator('#station-header').innerText(),/图书表待补/);
      assert.deepEqual(errors,[]);
      console.log(`${width}px: original intro, map in first viewport, seven sites, eight poems, exhibition links and legacy deep links: OK`);
      await ctx.close();
    }
  } finally { await browser.close(); }
})().catch(e=>{console.error(e);process.exitCode=1;});
